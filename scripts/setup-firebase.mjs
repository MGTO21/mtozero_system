/**
 * Wires a Firebase project into this app in one step.
 *
 * Paste the whole `firebaseConfig` snippet from the Firebase Console into a file
 * (or pipe it in), and this writes .env.local and patches the owner email inside
 * firestore.rules so the two can never drift apart.
 *
 * Usage:
 *   node scripts/setup-firebase.mjs --email you@gmail.com --config firebase-config.txt
 *   node scripts/setup-firebase.mjs --email you@gmail.com          (reads stdin)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function arg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 ? process.argv[i + 1] : undefined;
}

function fail(message) {
  console.error(`\n✖ ${message}\n`);
  process.exit(1);
}

const email = (arg('email') ?? '').trim().toLowerCase();
if (!email || !email.includes('@')) {
  fail('مطلوب بريد المالك:  node scripts/setup-firebase.mjs --email you@gmail.com --config firebase-config.txt');
}

const DEFAULT_CONFIG_FILE = 'firebase-config.txt';
const configPath = arg('config');
let raw;
if (configPath) {
  const full = join(ROOT, configPath);
  if (!existsSync(full)) fail(`لم أجد الملف: ${configPath}`);
  raw = readFileSync(full, 'utf8');
} else if (existsSync(join(ROOT, DEFAULT_CONFIG_FILE))) {
  // Convenience path: paste the snippet into firebase-config.txt and just run the script.
  raw = readFileSync(join(ROOT, DEFAULT_CONFIG_FILE), 'utf8');
  console.log(`• قرأت الإعدادات من ${DEFAULT_CONFIG_FILE}`);
} else if (!process.stdin.isTTY) {
  raw = readFileSync(0, 'utf8');
} else {
  fail(
    `الصق كتلة firebaseConfig في ملف ${DEFAULT_CONFIG_FILE} داخل مجلد المشروع، ثم أعد تشغيل الأمر.`,
  );
}

/** Pulls a value out of the pasted snippet, tolerating quotes and trailing commas. */
function pick(key) {
  const match = raw.match(new RegExp(`${key}\\s*:\\s*["'\`]([^"'\`]+)["'\`]`));
  return match?.[1]?.trim();
}

const config = {
  apiKey: pick('apiKey'),
  authDomain: pick('authDomain'),
  projectId: pick('projectId'),
  storageBucket: pick('storageBucket'),
  messagingSenderId: pick('messagingSenderId'),
  appId: pick('appId'),
};

const missing = Object.entries(config)
  .filter(([, v]) => !v)
  .map(([k]) => k);
if (missing.length) {
  fail(`القيم التالية ناقصة في الملف: ${missing.join(', ')}\nانسخ كتلة firebaseConfig كاملة من Firebase Console.`);
}

/* ---------- .env.local ---------- */

const envPath = join(ROOT, '.env.local');
const env = [
  '# Generated by scripts/setup-firebase.mjs — safe to edit by hand.',
  `NEXT_PUBLIC_FIREBASE_API_KEY=${config.apiKey}`,
  `NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=${config.authDomain}`,
  `NEXT_PUBLIC_FIREBASE_PROJECT_ID=${config.projectId}`,
  `NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=${config.storageBucket}`,
  `NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=${config.messagingSenderId}`,
  `NEXT_PUBLIC_FIREBASE_APP_ID=${config.appId}`,
  '',
  '# The first account signing in with this address becomes the owner.',
  `NEXT_PUBLIC_OWNER_EMAIL=${email}`,
  '',
  '# Optional full-resolution images on Cloudinary. Thumbnails work without these.',
  `NEXT_PUBLIC_CLOUDINARY_CLOUD_NAME=${arg('cloudinary-cloud') ?? ''}`,
  `NEXT_PUBLIC_CLOUDINARY_UPLOAD_PRESET=${arg('cloudinary-preset') ?? ''}`,
  '',
].join('\n');

if (existsSync(envPath)) {
  writeFileSync(`${envPath}.backup`, readFileSync(envPath));
  console.log('• حفظت نسخة من .env.local القديم في .env.local.backup');
}
writeFileSync(envPath, env, 'utf8');
console.log('✓ كتبت .env.local');

/* ---------- firestore.rules ---------- */

const rulesPath = join(ROOT, 'firestore.rules');
const rules = readFileSync(rulesPath, 'utf8');
const patched = rules.replace(
  /(function ownerEmail\(\)\s*\{\s*return\s*)'[^']*'/,
  `$1'${email}'`,
);

const current = rules.match(/function ownerEmail\(\)\s*\{\s*return\s*'([^']*)'/)?.[1];
if (current === email) {
  console.log(`✓ ownerEmail() في firestore.rules مضبوط أصلاً على ${email}`);
} else if (patched === rules) {
  console.warn('⚠ لم أستطع تعديل ownerEmail() في firestore.rules — عدّله يدوياً.');
} else {
  writeFileSync(rulesPath, patched, 'utf8');
  console.log(`✓ ضبطت ownerEmail() في firestore.rules على ${email}`);
}

console.log(`
المشروع: ${config.projectId}

الخطوات المتبقية (من Firebase Console):
  1. Authentication → فعّل Email/Password
  2. Firestore Database → أنشئها بوضع Production
  3. Firestore → تبويب Rules → الصق محتوى firestore.rules → Publish
  4. Authentication → Users → أضف مستخدماً بالبريد ${email}

ملاحظة: Storage غير مطلوب — صور المنتجات تُضغط وتُحفظ داخل Firestore.

ثم:  npm run dev
`);
